-- Athlete Medical Profiles
CREATE TABLE IF NOT EXISTS athlete_medical_profiles (
    id                              BINARY(16)   NOT NULL,
    athlete_user_id                 BINARY(16)   NOT NULL,
    blood_type                      VARCHAR(10),
    existing_conditions             TEXT,
    past_illnesses                  TEXT,
    previous_surgeries              TEXT,
    hospital_admissions             TEXT,
    known_allergies                 TEXT,
    current_medications             TEXT,
    family_cardiac_history          BOOLEAN      NOT NULL DEFAULT FALSE,
    exercise_symptoms               TEXT,
    vision_hearing_notes            TEXT,
    musculoskeletal_notes           TEXT,
    emergency_contact_name          VARCHAR(100),
    emergency_contact_phone         VARCHAR(30),
    emergency_contact_relation      VARCHAR(50),
    neurological_spinal_history     TEXT,
    functional_limitations          TEXT,
    assistive_equipment             TEXT,
    individual_emergency_care_notes TEXT,
    questionnaire_completed         BOOLEAN      NOT NULL DEFAULT FALSE,
    reviewed_by_medical_officer     BOOLEAN      NOT NULL DEFAULT FALSE,
    submitted_by                    BINARY(16),
    submitted_date                  DATETIME(6),
    last_reviewed_date              DATETIME(6),
    outstanding_clarifications      TEXT,
    created_date                    DATETIME(6)  NOT NULL,
    last_modified_date              DATETIME(6)  NOT NULL,
    created_by                      VARCHAR(255),
    last_modified_by                VARCHAR(255),
    PRIMARY KEY (id),
    UNIQUE KEY uk_amp_athlete (athlete_user_id),
    CONSTRAINT fk_amp_athlete FOREIGN KEY (athlete_user_id) REFERENCES users (id),
    INDEX idx_amp_athlete (athlete_user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- Medical Assessments
CREATE TABLE IF NOT EXISTS medical_assessments (
    id                          BINARY(16)   NOT NULL,
    athlete_user_id             BINARY(16)   NOT NULL,
    assessment_type             VARCHAR(50)  NOT NULL,
    assessment_date             DATETIME(6)  NOT NULL,
    clinician_user_id           BINARY(16)   NOT NULL,
    clinician_credentials       VARCHAR(200),
    blood_pressure_systolic     INT,
    blood_pressure_diastolic    INT,
    pulse_bpm                   INT,
    cardiovascular_findings     TEXT,
    respiratory_findings        TEXT,
    neurological_findings       TEXT,
    musculoskeletal_findings    TEXT,
    investigations_results      TEXT,
    clinical_findings           TEXT,
    recommendations             TEXT,
    participation_restrictions  TEXT,
    referrals_required          TEXT,
    follow_up_date              DATE,
    status                      VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',
    finalised_at                DATETIME(6),
    created_date                DATETIME(6)  NOT NULL,
    last_modified_date          DATETIME(6)  NOT NULL,
    created_by                  VARCHAR(255),
    last_modified_by            VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_ma_athlete   FOREIGN KEY (athlete_user_id)   REFERENCES users (id),
    CONSTRAINT fk_ma_clinician FOREIGN KEY (clinician_user_id) REFERENCES users (id),
    INDEX idx_ma_athlete   (athlete_user_id),
    INDEX idx_ma_clinician (clinician_user_id),
    INDEX idx_ma_status    (status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- Athlete Injuries
CREATE TABLE IF NOT EXISTS athlete_injuries (
    id                          BINARY(16)   NOT NULL,
    athlete_user_id             BINARY(16)   NOT NULL,
    camp_id                     BINARY(16),
    incident_date               DATETIME(6)  NOT NULL,
    reported_date               DATETIME(6)  NOT NULL,
    incident_location           VARCHAR(200),
    injury_context              VARCHAR(50),
    body_region                 VARCHAR(50),
    injury_category             VARCHAR(50),
    is_suspected_concussion     BOOLEAN      NOT NULL DEFAULT FALSE,
    mechanism_of_injury         TEXT,
    symptoms_reported           TEXT,
    severity                    VARCHAR(30),
    confirmed_diagnosis         TEXT,
    initial_response            TEXT,
    referral_details            TEXT,
    treatment_plan              TEXT,
    participation_restrictions  TEXT,
    rehabilitation_status       VARCHAR(50),
    return_to_sport_decision    TEXT,
    status                      VARCHAR(50)  NOT NULL DEFAULT 'REPORTED',
    reported_by                 BINARY(16)   NOT NULL,
    recorded_by                 BINARY(16),
    created_date                DATETIME(6)  NOT NULL,
    last_modified_date          DATETIME(6)  NOT NULL,
    created_by                  VARCHAR(255),
    last_modified_by            VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_ai_athlete  FOREIGN KEY (athlete_user_id) REFERENCES users (id),
    CONSTRAINT fk_ai_reporter FOREIGN KEY (reported_by)     REFERENCES users (id),
    INDEX idx_ai_athlete    (athlete_user_id),
    INDEX idx_ai_status     (status),
    INDEX idx_ai_concussion (is_suspected_concussion),
    INDEX idx_ai_camp       (camp_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- Medical Clearances
CREATE TABLE IF NOT EXISTS medical_clearances (
    id                          BINARY(16)   NOT NULL,
    athlete_user_id             BINARY(16)   NOT NULL,
    issued_by                   BINARY(16)   NOT NULL,
    related_assessment_id       BINARY(16),
    related_injury_id           BINARY(16),
    activity_scope              VARCHAR(200),
    status                      VARCHAR(50)  NOT NULL DEFAULT 'PENDING',
    decision_date               DATETIME(6),
    effective_date              DATE,
    expiry_date                 DATE,
    participation_restrictions  TEXT,
    required_accommodations     TEXT,
    follow_up_requirements      TEXT,
    conditional_reason          TEXT,
    revocation_reason           TEXT,
    revoked_by                  BINARY(16),
    revoked_at                  DATETIME(6),
    previous_clearance_id       BINARY(16),
    created_date                DATETIME(6)  NOT NULL,
    last_modified_date          DATETIME(6)  NOT NULL,
    created_by                  VARCHAR(255),
    last_modified_by            VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_mc_athlete    FOREIGN KEY (athlete_user_id)       REFERENCES users (id),
    CONSTRAINT fk_mc_issuer     FOREIGN KEY (issued_by)             REFERENCES users (id),
    CONSTRAINT fk_mc_assessment FOREIGN KEY (related_assessment_id) REFERENCES medical_assessments (id),
    CONSTRAINT fk_mc_injury     FOREIGN KEY (related_injury_id)     REFERENCES athlete_injuries (id),
    CONSTRAINT fk_mc_prev       FOREIGN KEY (previous_clearance_id) REFERENCES medical_clearances (id),
    INDEX idx_mc_athlete (athlete_user_id),
    INDEX idx_mc_status  (status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- Medical Documents
CREATE TABLE IF NOT EXISTS medical_documents (
    id                          BINARY(16)   NOT NULL,
    athlete_user_id             BINARY(16)   NOT NULL,
    related_assessment_id       BINARY(16),
    related_injury_id           BINARY(16),
    related_clearance_id        BINARY(16),
    document_category           VARCHAR(50)  NOT NULL,
    original_filename           VARCHAR(255) NOT NULL,
    stored_path                 VARCHAR(512) NOT NULL,
    content_type                VARCHAR(100) NOT NULL,
    file_size_bytes             BIGINT       NOT NULL,
    description                 VARCHAR(500),
    uploaded_by                 BINARY(16)   NOT NULL,
    created_date                DATETIME(6)  NOT NULL,
    last_modified_date          DATETIME(6)  NOT NULL,
    created_by                  VARCHAR(255),
    last_modified_by            VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_md_athlete    FOREIGN KEY (athlete_user_id)       REFERENCES users (id),
    CONSTRAINT fk_md_assessment FOREIGN KEY (related_assessment_id) REFERENCES medical_assessments (id),
    CONSTRAINT fk_md_injury     FOREIGN KEY (related_injury_id)     REFERENCES athlete_injuries (id),
    CONSTRAINT fk_md_clearance  FOREIGN KEY (related_clearance_id)  REFERENCES medical_clearances (id),
    INDEX idx_md_athlete    (athlete_user_id),
    INDEX idx_md_assessment (related_assessment_id),
    INDEX idx_md_injury     (related_injury_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
